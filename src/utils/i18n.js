export function formatCurrency(amount, currency = 'IDR', lang = 'id') {
  // Determine locale based on language, but also adjust if currency is USD
  const locale = lang === 'id' ? 'id-ID' : 'en-US';
  
  // IDR usually has no decimals in standard display
  const maximumFractionDigits = currency === 'IDR' ? 0 : 2;

  return new Intl.NumberFormat(locale, {
    style: 'currency',
    currency: currency,
    maximumFractionDigits
  }).format(amount || 0);
}
